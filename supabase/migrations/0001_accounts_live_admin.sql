  user_id uuid primary key references public.profiles (id) on delete cascade,
  data jsonb not null default '{}'::jsonb,
  updated_at timestamptz not null default now()
);

-- ---------- Live classes ----------
create table if not exists public.live_sessions (
  id uuid primary key default gen_random_uuid(),
  host_id uuid not null references public.profiles (id) on delete cascade,
  title text not null default 'Live class',
  room text not null,
  status text not null default 'live' check (status in ('live', 'ended')),
  section text not null default 'live',
  target jsonb,
  started_at timestamptz not null default now(),
  ended_at timestamptz,
  updated_at timestamptz not null default now()
);
create index if not exists live_sessions_status_idx on public.live_sessions (status, started_at desc);

-- ---------- Audit log ----------
create table if not exists public.audit_log (
  id bigint generated by default as identity primary key,
  actor_id uuid references public.profiles (id) on delete set null,
  actor_email text,
  action text not null,
  target text,
  details jsonb,
  created_at timestamptz not null default now()
);
create index if not exists audit_log_created_idx on public.audit_log (created_at desc);

-- ---------- Helpers ----------
create or replace function public.is_admin()
returns boolean language sql stable security definer set search_path = public as $$
  select coalesce((select role = 'admin' and status = 'active' from public.profiles where id = auth.uid()), false)
$$;

create or replace function public.is_staff()
returns boolean language sql stable security definer set search_path = public as $$
  select coalesce((select role in ('admin', 'teacher') and status = 'active' from public.profiles where id = auth.uid()), false)
$$;

create or replace function public.touch_updated_at()
returns trigger language plpgsql as $$
begin
  new.updated_at = now();
  return new;
end $$;

drop trigger if exists profiles_touch on public.profiles;
create trigger profiles_touch before update on public.profiles for each row execute function public.touch_updated_at();
drop trigger if exists study_records_touch on public.study_records;
create trigger study_records_touch before update on public.study_records for each row execute function public.touch_updated_at();
drop trigger if exists live_sessions_touch on public.live_sessions;
create trigger live_sessions_touch before update on public.live_sessions for each row execute function public.touch_updated_at();
drop trigger if exists app_settings_touch on public.app_settings;
create trigger app_settings_touch before update on public.app_settings for each row execute function public.touch_updated_at();

-- New auth user -> profile. The first account, and any address in admin_emails, becomes an admin.
create or replace function public.handle_new_user()
returns trigger language plpgsql security definer set search_path = public as $$
declare
  admins jsonb := coalesce((select value from public.app_settings where key = 'admin_emails'), '[]'::jsonb);
  wanted_role text := coalesce(new.raw_user_meta_data ->> 'role', 'student');
  final_role text := 'student';
begin
  if admins ? lower(new.email) or not exists (select 1 from public.profiles) then
    final_role := 'admin';
  elsif wanted_role in ('teacher', 'admin') and coalesce((new.raw_user_meta_data ->> 'created_by_admin')::boolean, false) then
    final_role := wanted_role;
  end if;
  insert into public.profiles (id, email, full_name, role)
  values (new.id, new.email, coalesce(new.raw_user_meta_data ->> 'full_name', ''), final_role)
  on conflict (id) do nothing;
  return new;
end $$;

drop trigger if exists on_auth_user_created on auth.users;
create trigger on_auth_user_created after insert on auth.users for each row execute function public.handle_new_user();

-- Admin-only account removal that does not need the service key: deleting the auth user cascades to the profile.
create or replace function public.admin_delete_user(target uuid)
returns void language plpgsql security definer set search_path = public, auth as $$
begin
  if not public.is_admin() then raise exception 'Only administrators can delete accounts.'; end if;
  if target = auth.uid() then raise exception 'You cannot delete your own account.'; end if;
  insert into public.audit_log (actor_id, actor_email, action, target, details)
  select auth.uid(), p.email, 'user.delete', t.email, jsonb_build_object('role', t.role)
  from public.profiles p, public.profiles t where p.id = auth.uid() and t.id = target;
  delete from auth.users where id = target;
end $$;

-- Lightweight "last seen" ping from the app.
create or replace function public.ping_presence()
returns void language sql security definer set search_path = public as $$
  update public.profiles set last_seen_at = now() where id = auth.uid()
$$;

