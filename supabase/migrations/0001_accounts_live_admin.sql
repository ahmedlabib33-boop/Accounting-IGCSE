drop policy if exists profiles_read_own on public.profiles;
create policy profiles_read_own on public.profiles for select to authenticated using (id = auth.uid() or public.is_staff());
drop policy if exists profiles_update_own on public.profiles;
create policy profiles_update_own on public.profiles for update to authenticated
  using (id = auth.uid()) with check (id = auth.uid() and role = (select role from public.profiles where id = auth.uid()) and status = (select status from public.profiles where id = auth.uid()));
drop policy if exists profiles_admin_update on public.profiles;
create policy profiles_admin_update on public.profiles for update to authenticated using (public.is_admin()) with check (public.is_admin());

drop policy if exists settings_public_read on public.app_settings;
create policy settings_public_read on public.app_settings for select to anon, authenticated
  using (key in ('registration_open', 'maintenance', 'announcement', 'teacher_name', 'jitsi_domain') or public.is_admin());
drop policy if exists settings_admin_write on public.app_settings;
create policy settings_admin_write on public.app_settings for all to authenticated using (public.is_admin()) with check (public.is_admin());

drop policy if exists study_own on public.study_records;
create policy study_own on public.study_records for all to authenticated using (user_id = auth.uid()) with check (user_id = auth.uid());
drop policy if exists study_staff_read on public.study_records;
create policy study_staff_read on public.study_records for select to authenticated using (public.is_staff());

drop policy if exists live_read on public.live_sessions;
create policy live_read on public.live_sessions for select to authenticated using (true);
drop policy if exists live_staff_write on public.live_sessions;
create policy live_staff_write on public.live_sessions for all to authenticated using (public.is_staff()) with check (public.is_staff());

drop policy if exists audit_admin_read on public.audit_log;
create policy audit_admin_read on public.audit_log for select to authenticated using (public.is_admin());
drop policy if exists audit_staff_insert on public.audit_log;
create policy audit_staff_insert on public.audit_log for insert to authenticated with check (public.is_staff() and actor_id = auth.uid());

-- Realtime: signed-in users may join private class channels (broadcast + presence).
drop policy if exists class_channels_read on realtime.messages;
create policy class_channels_read on realtime.messages for select to authenticated
  using ((select realtime.topic()) like 'class:%' and realtime.messages.extension in ('broadcast', 'presence'));
drop policy if exists class_channels_write on realtime.messages;
create policy class_channels_write on realtime.messages for insert to authenticated
  with check ((select realtime.topic()) like 'class:%' and realtime.messages.extension in ('broadcast', 'presence'));

-- Students learn that a class started or ended through table changes.
do $$ begin
  if not exists (select 1 from pg_publication_tables where pubname = 'supabase_realtime' and tablename = 'live_sessions') then
    alter publication supabase_realtime add table public.live_sessions;
  end if;
  if not exists (select 1 from pg_publication_tables where pubname = 'supabase_realtime' and tablename = 'app_settings') then
    alter publication supabase_realtime add table public.app_settings;
  end if;
  if not exists (select 1 from pg_publication_tables where pubname = 'supabase_realtime' and tablename = 'profiles') then
    alter publication supabase_realtime add table public.profiles;
  end if;
end $$;

grant usage on schema public to anon, authenticated;
grant select on public.app_settings to anon;
